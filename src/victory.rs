// trig вызывается напрямую из кода игры (cdecl) — как и в C++
#[no_mangle]
pub extern "C" fn trig() {
    unsafe {
        let lvl = rb(LEVEL_OBJ);
        if a_custom != 0 {
            v_custom(false);
        } else if lvl < 52 {
            TRIGGERS[lvl as usize](false);
        } else {
            v_custom(false);
        }
        first_step = false;
    }
}

pub unsafe fn trig_init() {
    first_step = true;
    let lvl = rb(LEVEL_OBJ);
    if a_custom != 0 {
        v_custom(true);
    } else if lvl < 52 {
        TRIGGERS[lvl as usize](true);
    } else {
        v_custom(true);
    }
}

